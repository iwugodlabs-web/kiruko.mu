def main():
    engine = config.get_engine_from_settings()
    if not engine:
        print("[pre_migrate] No DB engine — skipping")
        return

    with engine.connect() as conn:
        # Without this, an ALTER TABLE stuck behind another session's lock on
        # the same table hangs indefinitely — no exception, no log line, just
        # a silent boot that never reaches uvicorn until DO's health check
        # times out. A short lock_timeout turns that into a fast, caught
        # exception (below) so one contended table can't block every other
        # column, or the whole deploy.
        conn.execute(text("SET lock_timeout = '5s'"))
        for table, column, col_def in CRITICAL_COLUMNS:
            try:
                conn.execute(
                    text(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {col_def}")
                )
                conn.commit()
                print(f"[pre_migrate] ✓ {table}.{column} ensured")
            except Exception as e:
                print(f"[pre_migrate] Warning — {table}.{column}: {e}")
                try:
                    conn.rollback()
                except Exception:
                    pass

        # Ensure whole tables that may be missing (alembic stamped ahead).
        for table_name, statements in CRITICAL_TABLES:
            try:
                for stmt in statements:
                    conn.execute(text(stmt))
                conn.commit()
                print(f"[pre_migrate] ✓ table {table_name} ensured")
            except Exception as e:
                print(f"[pre_migrate] Warning — table {table_name}: {e}")
                try:
                    conn.rollback()
                except Exception:
                    pass


# NOTE: ensure_model_schema() is intentionally NOT called from main(). main()
# runs BEFORE `alembic upgrade head`; the comprehensive model-diff must run
# AFTER it (see scripts/post_migrate.py), otherwise it would pre-create a column
# a brand-new forward migration then tries to add — failing that (non-idempotent)
# migration and aborting the deploy. It is invoked from post_migrate.py instead.
def ensure_model_schema():
    """Bring the physical schema up to the ORM model definitions, idempotently.

    Root cause this addresses: prod's alembic_version is stamped ahead of the
    real schema (a create_all + stamp bootstrap), so `alembic upgrade head`
    no-ops and any migration that adds a table/column is silently skipped —
    surfacing later as UndefinedTable / UndefinedColumn 500s, one casualty at a
    time (employee_country_assignments, then payroll_runs.fx_snapshot, …).

    Instead of hand-listing each casualty, diff the live schema against the ORM
    metadata and repair drift:
      * create any missing TABLE from its model definition (FK-dependency order), and
      * add any missing COLUMN as NULLABLE — existence is what stops the 500; we
        deliberately do NOT force NOT NULL / defaults, so ADD COLUMN can never
        fail on a populated table.

    Safety: a correct schema is a complete no-op. Every step is
    checkfirst / IF NOT EXISTS / per-object try-except, and the caller treats any
    failure as non-fatal — so this can never fail a boot. RLS/triggers/CHECKs
    that live only in migrations are intentionally not reconstructed here; the
    goal is strictly "no missing table/column 500s", not a migration replacement.
    """
    import core.model  # noqa: F401 — populates Base.metadata with every model
    from core.base_class import Base
    from sqlalchemy import inspect as sa_inspect

    engine = config.get_engine_from_settings()
    if not engine:
        print("[schema_ensure] No DB engine — skipping")
        return

    created_tables = 0
    added_cols = 0
    insp = sa_inspect(engine)
    existing_tables = set(insp.get_table_names())

    with engine.connect() as conn:
        # Hard time caps so a slow/blocked statement can NEVER hang the boot: a
        # DDL stuck behind another session's lock errors out after lock_timeout
        # (caught below) instead of waiting forever, so this can't wedge a deploy.
        # Every statement here is purely additive (CREATE/ADD ... IF NOT EXISTS),
        # so a timeout just means "retry next boot" — never data loss.
        for guc in ("SET lock_timeout = '5s'", "SET statement_timeout = '30s'"):
            try:
                conn.execute(text(guc))
                conn.commit()
            except Exception:
                pass

        # 1) Missing tables — create from the model (sorted_tables = FK order).
        for table in Base.metadata.sorted_tables:
            if table.name in existing_tables:
                continue
            try:
                table.create(bind=conn, checkfirst=True)
                conn.commit()
                created_tables += 1
                print(f"[schema_ensure] ✓ created missing table {table.name}")
            except Exception as e:
                print(f"[schema_ensure] table {table.name}: {e}")
                try:
                    conn.rollback()
                except Exception:
                    pass

        # 2) Missing columns on existing tables — ADD COLUMN IF NOT EXISTS
        # (nullable, no default → a metadata-only change in Postgres, so the
        # ACCESS EXCLUSIVE lock is held for microseconds; no table rewrite, no
        # meaningful contention with the still-serving old instance).
        insp = sa_inspect(engine)
        live_tables = set(insp.get_table_names())
        for table in Base.metadata.sorted_tables:
            if table.name not in live_tables:
                continue
            try:
                existing_cols = {c["name"] for c in insp.get_columns(table.name)}
            except Exception:
                continue
            for col in table.columns:
                if col.name in existing_cols:
                    continue
                try:
                    coltype = col.type.compile(dialect=engine.dialect)
                except Exception as e:
                    print(f"[schema_ensure] skip {table.name}.{col.name} (type compile failed: {e})")
                    continue
                try:
                    conn.execute(text(
                        f'ALTER TABLE "{table.name}" ADD COLUMN IF NOT EXISTS "{col.name}" {coltype}'
                    ))
                    conn.commit()
                    added_cols += 1
                    print(f"[schema_ensure] ✓ added {table.name}.{col.name} ({coltype})")
                except Exception as e:
                    print(f"[schema_ensure] {table.name}.{col.name}: {e}")
                    try:
                        conn.rollback()
                    except Exception:
                        pass

    if created_tables == 0 and added_cols == 0:
        print("[schema_ensure] schema matches models — nothing to repair")
    else:
        print(f"[schema_ensure] repaired drift: {created_tables} table(s), {added_cols} column(s)")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"[pre_migrate] Non-fatal error: {e}")
        sys.exit(0)
