# Whole TABLES observed missing in production because the alembic stamp is ahead
# of the real schema (create_all/stamp bootstrap), so `alembic upgrade head`
# no-ops and never runs the CREATE. pre_migrate only handled missing COLUMNS;
# a missing table needs the same treatment. Each statement is idempotent
# (CREATE TABLE/INDEX IF NOT EXISTS, CREATE OR REPLACE, DROP ... IF EXISTS), so
# it's safe on every boot and a no-op once the table exists. RLS enablement is
# intentionally NOT replicated here — RLS is not active on prod yet, and forcing
# it on one table out of band could block access; the RLS migration owns that.
